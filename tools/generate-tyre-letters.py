"""Rebuild centred tyre lettering from the bundled OFL Russo One font (fonttools)."""
import json, pathlib, re
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen
root = pathlib.Path(__file__).resolve().parents[1]
font = TTFont(root / 'renderer/fonts/russoone/RussoOne-Regular.ttf')
glyphs, cmap = font.getGlyphSet(), font.getBestCmap()
result = {}
for text in ['H', 'M', 'S', 'SS', 'US', 'HS', 'SH', 'I', 'W']:
    bounds = BoundsPen(glyphs)
    advance = 0
    for char in text:
        glyph = glyphs[cmap[ord(char)]]
        glyph.draw(TransformPen(bounds, (1, 0, 0, 1, advance, 0)))
        advance += glyph.width
    x0, y0, x1, y1 = bounds.bounds
    scale = min(22 / (y1-y0), 40 / (x1-x0))
    pen = SVGPathPen(glyphs, ntos=lambda n: str(round(n, 3)))
    advance = 0
    for char in text:
        glyph = glyphs[cmap[ord(char)]]
        glyph.draw(TransformPen(pen, (scale, 0, 0, -scale, 50-(x0+x1)*scale/2+advance*scale, 50+(y0+y1)*scale/2)))
        advance += glyph.width
    result[text] = pen.getCommands()
file = root / 'renderer/weatherwidgets.js'
source = file.read_text(encoding='utf-8')
block = '  // BEGIN TYRE LETTERS: generated by tools/generate-tyre-letters.py; Russo One OFL in fonts/russoone.\n  const TYRE_LETTERS = ' + json.dumps(result, separators=(',', ':')) + ';\n  // END TYRE LETTERS'
if '// BEGIN TYRE LETTERS' in source:
    source = re.sub(r'  // BEGIN TYRE LETTERS.*?  // END TYRE LETTERS', lambda _: block, source, flags=re.S)
else:
    source = source.replace('  // ---- the pictures', block + '\n  // ---- the pictures', 1)
file.write_text(source, encoding='utf-8', newline='\n')
