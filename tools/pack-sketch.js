// Packs firmware/SlotForgeBox/* into renderer/arduinosketch.js, so the app can offer the sketch as a download without reading files at run time.
// Run after every change to the firmware: node tools/pack-sketch.js   (tests/arduinosketch.test.js fails when the two are out of step)
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..'), dir = path.join(root, 'firmware', 'SlotForgeBox');
const files = fs.readdirSync(dir).filter(f => /\.(ino|h|cpp|md|txt)$/.test(f)).sort();
const version = (/#define SFB_VERSION "([^"]+)"/.exec(fs.readFileSync(path.join(dir, 'settings.h'), 'utf8')) || [])[1] || '0.0.0';
const entries = files.map(f => `    ${JSON.stringify('SlotForgeBox/' + f)}: ${JSON.stringify(fs.readFileSync(path.join(dir, f), 'utf8'))}`);
const out = `// GENERATED by tools/pack-sketch.js from firmware/SlotForgeBox - do not edit here. The Arduino sketch of the SlotForge box, embedded so the app can hand it out.
(function (root) {
  const api = { version: ${JSON.stringify(version)}, files: {\n${entries.join(',\n')}\n  } };
  root.ArduinoSketch = api;
  if (typeof module !== 'undefined') module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
`;
fs.writeFileSync(path.join(root, 'renderer', 'arduinosketch.js'), out);
console.log(`packed ${files.length} files, firmware ${version}`);
