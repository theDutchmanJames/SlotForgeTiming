const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),DB=require('../db'),M=require('../renderer/multiclass');
fs.mkdirSync(path.resolve(__dirname,'../.tmp-test'),{recursive:true});
const dir=fs.mkdtempSync(path.resolve(__dirname,'../.tmp-test/class-delete-')),file=path.join(dir,'db.json');
const db=new DB(file);
const a=db.add('raceclasses',{name:'GT3'}),b=db.add('raceclasses',{name:'Prototype'});
const car=db.add('slotcars',{brand:'NSR',model:'GT',raceClass:a.id});
const driver=db.add('drivers',{name:'James',raceClass:a.id});
const team=db.add('teams',{name:'Team',raceClass:a.id});
const other=db.add('slotcars',{brand:'Other',raceClass:b.id});
const profile=db.add('multiclasssystems',M.clean({name:'Mixed',assignment:'roster',classes:[a,b],driverClasses:[{driverId:driver.id,classId:a.id},{driverId:'other',classId:b.id}]}));
const only=db.add('multiclasssystems',M.clean({name:'GT only',classes:[a]}));
const frozen=M.freeze(profile,[a,b]);
const history={date:'2026-10-28',multiclass:frozen,standings:[{driverId:driver.id,raceClass:a.id,className:'GT3',laps:10}],heatResults:[{rows:[{raceClass:a.id,classPoints:25}]}]};
const session=db.saveSession(history,[]),before=JSON.stringify(db.list('sessions'));
const resume={v:1,race:{multiclass:frozen},eng:{cars:[{raceClass:a.id}]}};db.setResume(resume);
db.remove('raceclasses',a.id);
assert.equal(db.list('raceclasses').length,1);
for(const [table,row] of [['slotcars',car],['drivers',driver],['teams',team]])assert.equal(db.list(table).find(x=>x.id===row.id).raceClass,'');
assert.equal(db.list('slotcars').find(x=>x.id===other.id).raceClass,b.id);
assert.deepEqual(db.list('multiclasssystems').find(x=>x.id===profile.id).classes.map(c=>c.id),[b.id]);
assert.deepEqual(db.list('multiclasssystems').find(x=>x.id===profile.id).driverClasses,[{driverId:'other',classId:b.id}]);
assert.equal(db.list('multiclasssystems').find(x=>x.id===only.id).classes.length,0);
assert(M.validate(db.list('multiclasssystems').find(x=>x.id===only.id),[]).length>0);
assert.equal(JSON.stringify(db.list('sessions')),before);
assert.deepEqual(db.getResume(),resume);
assert.equal(frozen.classes[0].name,'GT3');
const reopened=new DB(file);assert.equal(reopened.list('raceclasses').length,1);assert.equal(JSON.stringify(reopened.list('sessions')),before);
assert.equal(reopened.list('slotcars').find(x=>x.id===car.id).raceClass,'');
db.remove('raceclasses','missing');assert.equal(JSON.stringify(db.list('sessions')),before);
db.remove('raceclasses',b.id);assert.equal(db.list('raceclasses').length,0);
assert.equal(db.list('multiclasssystems').find(x=>x.id===profile.id).driverClasses.length,0);
const Transfer=require('../transfer'),bundle=Transfer.collect(db.data,{sessions:[session]});
assert.equal(bundle.items.raceclasses.length,2);
const target=new DB(path.join(dir,'imported.json'));Transfer.apply(target,bundle);
const imported=target.list('sessions')[0];
assert.equal(imported.multiclass.classes.length,2);
assert(imported.multiclass.classes.every(c=>c.id));
assert.notEqual(imported.multiclass.classes[0].id,imported.multiclass.classes[1].id);
assert.equal(imported.standings[0].raceClass,imported.multiclass.classes[0].id);
assert.equal(imported.heatResults[0].rows[0].raceClass,imported.multiclass.classes[0].id);
assert.equal(db.list('raceclasses').length,0,'export must not resurrect deleted labels in the source database');
console.log('Race Class deletion: current references, empty-system validation, unrelated classes, saved results, active-event recovery, persistence and unused labels pass.');
